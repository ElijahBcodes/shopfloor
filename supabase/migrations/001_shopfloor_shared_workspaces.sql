create or replace function public.create_shop_invite(p_shop_id uuid)
returns text
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  invite_code text;
begin
  if auth.uid() is null or not exists (
    select 1
    from public.shop_members
    where shop_id = p_shop_id and user_id = auth.uid() and role = 'owner'
  ) then
    raise exception 'Only a shop owner can create an invite';
  end if;

  invite_code := encode(extensions.gen_random_bytes(24), 'hex');
  insert into public.shop_invites (shop_id, token_hash, created_by, expires_at)
  values (
    p_shop_id,
    encode(extensions.digest(convert_to(invite_code, 'UTF8'), 'sha256'), 'hex'),
    auth.uid(),
    now() + interval '7 days'
  );
  return invite_code;
end;
$$;

create or replace function public.join_shop(p_invite_code text)
returns uuid
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  target_shop_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Sign in before joining a shop';
  end if;
  if p_invite_code is null or char_length(trim(p_invite_code)) <> 48 then
    raise exception 'Invite code is invalid, expired, or already used';
  end if;

  update public.shop_invites
  set redeemed_at = now()
  where token_hash = encode(extensions.digest(convert_to(trim(p_invite_code), 'UTF8'), 'sha256'), 'hex')
    and redeemed_at is null
    and expires_at > now()
  returning shop_id into target_shop_id;

  if target_shop_id is null then
    raise exception 'Invite code is invalid, expired, or already used';
  end if;

  insert into public.shop_members (shop_id, user_id, role)
  values (target_shop_id, auth.uid(), 'member')
  on conflict (shop_id, user_id) do nothing;

  return target_shop_id;
end;
$$;

create or replace function public.change_job_status(p_shop_id uuid, p_job_number bigint, p_status text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  target_job public.jobs%rowtype;
  target_machine_status text;
begin
  if auth.uid() is null or not public.is_shop_member(p_shop_id) then
    raise exception 'You are not a member of this shop';
  end if;
  if p_status not in ('in-progress', 'complete') then
    raise exception 'Unsupported job status';
  end if;

  select * into target_job
  from public.jobs
  where shop_id = p_shop_id and job_number = p_job_number
  for update;

  if not found then
    raise exception 'Job not found';
  end if;

  if p_status = 'in-progress' then
    if target_job.status not in ('queued', 'paused') or target_job.machine_id is null then
      raise exception 'This job cannot be started until it has an available machine';
    end if;

    select status into target_machine_status
    from public.machines
    where shop_id = p_shop_id and id = target_job.machine_id
    for update;

    if target_machine_status is distinct from 'idle' then
      raise exception 'The assigned machine is not idle';
    end if;

    update public.jobs
    set status = 'in-progress'
    where shop_id = p_shop_id and job_number = p_job_number;
    update public.machines
    set status = 'running', utilization = greatest(utilization, 55)
    where shop_id = p_shop_id and id = target_job.machine_id;
  else
    update public.jobs
    set status = 'complete', progress = 100
    where shop_id = p_shop_id and job_number = p_job_number;

    if not exists (
      select 1 from public.jobs
      where shop_id = p_shop_id
        and machine_id = target_job.machine_id
        and job_number <> p_job_number
        and status = 'in-progress'
    ) then
      update public.machines
      set status = 'idle', utilization = 0
      where shop_id = p_shop_id and id = target_job.machine_id;
    end if;
  end if;
end;
$$;

create or replace function public.toggle_machine(p_shop_id uuid, p_machine_id text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_status text;
begin
  if auth.uid() is null or not public.is_shop_member(p_shop_id) then
    raise exception 'You are not a member of this shop';
  end if;

  select status into current_status
  from public.machines
  where shop_id = p_shop_id and id = p_machine_id
  for update;

  if not found then
    raise exception 'Machine not found';
  end if;

  if current_status = 'running' then
    update public.jobs
    set status = 'paused'
    where shop_id = p_shop_id and machine_id = p_machine_id and status = 'in-progress';
    update public.machines
    set status = 'idle', utilization = 0
    where shop_id = p_shop_id and id = p_machine_id;
  elsif current_status = 'setup' then
    update public.machines
    set status = 'idle', utilization = 0
    where shop_id = p_shop_id and id = p_machine_id;
  elsif current_status = 'idle' then
    if exists (
      select 1 from public.jobs
      where shop_id = p_shop_id and machine_id = p_machine_id and status = 'in-progress'
    ) then
      raise exception 'A job is already running on this machine';
    end if;
    update public.machines
    set status = 'running', utilization = greatest(utilization, 35)
    where shop_id = p_shop_id and id = p_machine_id;
  else
    raise exception 'This machine is in maintenance';
  end if;
end;
$$;

