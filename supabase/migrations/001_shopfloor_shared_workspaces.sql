-- ShopFloor shared workspaces, authenticated access, and starter board data.
create extension if not exists pgcrypto with schema extensions;

create table if not exists public.shops (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 80),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.shop_members (
  shop_id uuid not null references public.shops(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'member')),
  joined_at timestamptz not null default now(),
  primary key (shop_id, user_id)
);

create table if not exists public.shop_invites (
  id uuid primary key default gen_random_uuid(),
  shop_id uuid not null references public.shops(id) on delete cascade,
  token_hash text not null unique,
  created_by uuid not null references auth.users(id) on delete cascade,
  expires_at timestamptz not null,
  redeemed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.machines (
  shop_id uuid not null references public.shops(id) on delete cascade,
  id text not null check (char_length(trim(id)) between 1 and 24),
  make text not null default '',
  name text not null,
  type text not null default '',
  status text not null default 'idle' check (status in ('running', 'idle', 'setup', 'maintenance')),
  utilization smallint not null default 0 check (utilization between 0 and 100),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (shop_id, id)
);

create table if not exists public.jobs (
  job_number bigint generated by default as identity primary key,
  shop_id uuid not null references public.shops(id) on delete cascade,
  part_number text not null default '',
  title text not null check (char_length(trim(title)) between 1 and 120),
  material text not null default '',
  quantity integer not null default 1 check (quantity > 0),
  status text not null default 'queued' check (status in ('queued', 'in-progress', 'paused', 'complete')),
  machine_id text,
  progress smallint not null default 0 check (progress between 0 and 100),
  due_date date not null,
  due_time time not null default '15:00',
  priority text not null default 'normal' check (priority in ('urgent', 'high', 'normal')),
  operator text not null default '',
  operation text not null default '',
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint jobs_machine_in_same_shop
    foreign key (shop_id, machine_id)
    references public.machines(shop_id, id)
    on update cascade on delete restrict
);

create index if not exists jobs_shop_status_due_idx
  on public.jobs (shop_id, status, due_date);
create index if not exists shop_members_user_idx
  on public.shop_members (user_id, shop_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
revoke all on function public.set_updated_at() from public;

drop trigger if exists machines_set_updated_at on public.machines;
create trigger machines_set_updated_at
  before update on public.machines
  for each row execute function public.set_updated_at();

drop trigger if exists jobs_set_updated_at on public.jobs;
create trigger jobs_set_updated_at
  before update on public.jobs
  for each row execute function public.set_updated_at();

create or replace function public.is_shop_member(p_shop_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.shop_members
    where shop_id = p_shop_id
      and user_id = auth.uid()
  );
$$;

revoke all on function public.is_shop_member(uuid) from public;
grant execute on function public.is_shop_member(uuid) to authenticated;

